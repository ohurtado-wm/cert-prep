export function translate(locale: Locale, key: MessageKey, values: Record<string, string | number> = {}) {
  const singular = values.count === 1 || values.count === '1'
  const message = (singular && singularMessages[locale][key]) || messages[locale][key]
  return message.replace(/\{(\w+)\}/g, (_match, name: string) => String(values[name] ?? ''))
}

export function getTranslationKeys(locale: Locale) {
  return Object.keys(messages[locale])
}
